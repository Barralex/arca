_lang = "en"


def system_language() -> str:
    if sys.platform == "win32":
        try:
            import ctypes

            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            return "es" if lang_id & 0x3FF == 0x0A else "en"  # 0x0A: primary language id of Spanish
        except (AttributeError, OSError):
            pass
    value = os.environ.get("LANG") or (locale.getlocale()[0] or "")
    return "es" if value.lower().startswith("es") else "en"


def set_language(code: str) -> str:
    global _lang
    _lang = code if code in LANGS else system_language()
    return _lang


def language() -> str:
    return _lang


def t(key: str, **values: object) -> str:
    pair = STRINGS.get(key)
    if pair is None:
        return key
    text = pair[LANGS.index(_lang)]
    return text.format(**values) if values else text
